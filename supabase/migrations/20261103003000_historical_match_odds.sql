create table if not exists public.historical_match_odds (
  id bigint generated by default as identity primary key,
  match_date date not null,
  league text not null,
  home_team text not null,
  away_team text not null,
  market text not null check (market in ('home', 'draw', 'away')),
  bookmaker text not null,
  odds_type text not null check (odds_type in ('prediction', 'closing')),
  odds numeric not null check (odds > 1),
  captured_at timestamptz not null default now(),
  source text,
  model_version text,
  created_at timestamptz not null default now(),
  unique (match_date, league, home_team, away_team, market, bookmaker, odds_type)
);

create index if not exists historical_match_odds_lookup_idx
  on public.historical_match_odds (
    match_date, league, home_team, away_team, market, odds_type
  );

create index if not exists historical_match_odds_bookmaker_idx
  on public.historical_match_odds (bookmaker, captured_at);
