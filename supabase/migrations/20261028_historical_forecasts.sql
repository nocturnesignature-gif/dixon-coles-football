create table if not exists public.historical_forecasts (
  id bigint generated by default as identity primary key,
  match_date date not null,
  league text not null,
  home_team text not null,
  away_team text not null,
  home_goals int not null,
  away_goals int not null,
  actual_outcome text not null check (actual_outcome in ('home','draw','away')),
  home_probability numeric not null check (home_probability >= 0 and home_probability <= 1),
  draw_probability numeric not null check (draw_probability >= 0 and draw_probability <= 1),
  away_probability numeric not null check (away_probability >= 0 and away_probability <= 1),
  log_loss numeric not null,
  brier_score numeric not null,
  model_version text not null default 'dixon_coles_walkforward_v1',
  created_at timestamptz not null default now(),
  unique (match_date, league, home_team, away_team, model_version)
);

create index if not exists historical_forecasts_outcome_idx
  on public.historical_forecasts (actual_outcome);

create index if not exists historical_forecasts_date_idx
  on public.historical_forecasts (match_date);
